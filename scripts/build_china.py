#!/usr/bin/env python3
"""Merge blackmatrix7's Loon China rules and DOMAIN-SET with local additions.

Only outputs Loon classical two-/three-field rules (without policy names).
If an upstream source is unavailable or unexpectedly changes format/size,
fail without replacing the previously published rules.
"""

from __future__ import annotations

import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "rules" / "China.list"
CUSTOM = ROOT / "rules" / "China_Custom.list"
UPSTREAM_CLASSICAL = (
    "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/"
    "rule/Loon/China/China.list"
)
UPSTREAM_DOMAIN_SET = (
    "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/"
    "rule/Loon/China/China_Domain.list"
)
ALLOWED_TYPES = {
    "DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "USER-AGENT",
    "IP-CIDR", "IP-CIDR6",
}
DOMAIN_PATTERN = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\Z")


def download(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "LoonRules-China-Updater/1.0"})
    with urllib.request.urlopen(req, timeout=45) as res:
        text = res.read().decode("utf-8-sig")
    if not text or "<html" in text[:250].lower():
        raise ValueError(f"Invalid upstream response from {url}")
    return text


def substantive_lines(text: str) -> list[str]:
    return [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def classical(text: str, label: str) -> list[str]:
    rules = substantive_lines(text)
    for rule in rules:
        kind, sep, value = rule.partition(",")
        if not sep or kind not in ALLOWED_TYPES or not value.strip():
            raise ValueError(f"Unsupported {label} rule: {rule!r}")
        # Rule-provider content has no policy. Third field is permitted only for IP no-resolve.
        fields = rule.split(",")
        if len(fields) > 2 and not (
            len(fields) == 3
            and kind in {"IP-CIDR", "IP-CIDR6"}
            and fields[2].lower() == "no-resolve"
        ):
            raise ValueError(f"Unexpected extra fields in {label}: {rule!r}")
    return rules


def domain_set(text: str) -> list[str]:
    rules = []
    for line in substantive_lines(text):
        if line.startswith("."):
            kind, domain = "DOMAIN-SUFFIX", line[1:]
        else:
            kind, domain = "DOMAIN", line
        if not DOMAIN_PATTERN.fullmatch(domain):
            raise ValueError(f"Unexpected DOMAIN-SET entry: {line!r}")
        rules.append(f"{kind},{domain.lower()}")
    return rules


def build() -> str:
    custom = classical(CUSTOM.read_text(encoding="utf-8-sig"), "custom")
    upstream = classical(download(UPSTREAM_CLASSICAL), "China.list")
    domains = domain_set(download(UPSTREAM_DOMAIN_SET))
    if len(upstream) < 50 or len(domains) < 3000:
        raise ValueError(
            f"Upstream seems incomplete: China={len(upstream)}, DOMAIN-SET={len(domains)}"
        )

    merged = []
    seen = set()
    for rule in [*custom, *upstream, *domains]:
        if rule not in seen:
            seen.add(rule)
            merged.append(rule)

    heading = [
        "# NAME: China (blackmatrix7 + custom)",
        "# FORMAT: Loon classical rule subscription",
        "# POLICY: DIRECT (set in Loon subscription, not in this file)",
        "# AUTO-GENERATED: do not edit this file; edit rules/China_Custom.list",
        f"# SOURCE: {UPSTREAM_CLASSICAL}",
        f"# SOURCE: {UPSTREAM_DOMAIN_SET}",
        f"# RULES: {len(merged)} (custom {len(custom)}, upstream {len(upstream)} + {len(domains)})",
        "",
    ]
    return "\n".join([*heading, *merged, ""])


def main() -> None:
    output = build()
    existing = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if output == existing:
        print(f"Already current: {OUTPUT}")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(output, encoding="utf-8")
        print(f"Updated {OUTPUT}: {sum(line.startswith(('DOMAIN,', 'DOMAIN-SUFFIX,', 'DOMAIN-KEYWORD,', 'USER-AGENT,', 'IP-CIDR,', 'IP-CIDR6,')) for line in output.splitlines())} rules")


if __name__ == "__main__":
    main()
